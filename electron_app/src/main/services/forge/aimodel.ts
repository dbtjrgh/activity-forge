/**
 * **모델을 못 박는다** (2026-09-18).
 *
 * 안 박으면 `claude -p` 가 **계정 기본 모델을 따라간다.** 사람이 `/model` 을
 * 한 번 바꾸면 이 도구가 재 둔 값이 **조용히 다른 모델의 값**이 된다.
 * 2026-09-18 에 실제로 그랬다 — 기본이 `claude-opus-5` 로 가 있어, 같은
 * 브리프 하나가 **68~126초 · $0.35** 였다(2026-09-17 기록은 29초 · $0.225).
 * 빈 폴더에서 같은 브리프를 세 꼴로 재서 갈랐다(`--output-format json` 의 `usage`):
 *
 *   기본(opus-5[1m])   68초 · 올림 7,523 · 출력 1,251 · **$0.351**
 *   `--effort low`     87초 · 올림 13,130 · 출력 462 · $0.554  ← 도움 안 됨
 *   **sonnet-5**       **32초** · 올림 5,215 · 출력 2,344 · **$0.044**
 *
 * 이 일은 「표 읽고 표로 답하기」다. 답은 **기계가 다시 검산하므로**(`brief.ts`·
 * `revise.ts`) 더 비싼 모델의 값어치가 여기서는 작다. 바꿀 때는 **재고 바꾼다.**
 *
 * **2026-09-29 사용자 결정으로 opus-5-5 로 바꿨다** (「바꿔」). 값이 한 번에 여덟 배쯤 든다 —
 * M1 의 ENL1 한 칸에서 완성본과 다른 값이 sonnet 16 · opus 10 이었던 것을 보고 정했다.
 * 싸게 돌리려면 `FORGE_AI_MODEL=claude-sonnet-5`.
 *
 * **2026-09-30 사용자 결정으로 sonnet-5-5 로 바꿨다** (9-28 에 나온 모델 — Opus 5.5 에 거의 붙고, 한 일당 값은 더 낮다).
 * 한 번 불러 봄: 답 정상 · $0.065(껍데기 포함). 이 CLI 가 이름을 목록에 안 올려 `unrecognized_model` 경고가
 * stderr 에 뜨지만 답은 온다. 조언자(advisor)도 꺼진다 — 사람용 설정이 따라와 12배가 되던 함정이 없어진다.
 * (그 경고는 2026-10-02 에 로그인이 풀려서였다 — 로그인 뒤에는 안 뜬다.)
 *
 * **2026-10-02 사용자 결정으로 opus-5-5 로 다시 바꿨다** (「토큰 신경 안 써도 될듯 오푸스5.5가 좀 많이 좋아서」) — 값보다 품질.
 * 같은 날 통째로 맡기기(`whole.ts`)를 넣으며 정했다.
 */
const DEFAULT_MODEL = 'claude-opus-5-5'
/**
 * **견줘 보려고 바꿀 수 있다** (2026-09-28) — `FORGE_AI_MODEL=claude-sonnet-5`. 안 심으면 위 기본값이다.
 * 녹음 열쇠에 모델이 들어간다(`tapeKey`) — 안 그러면 다른 모델로 녹음된 답이 이 모델 답처럼 틀어진다.
 */
export const MODEL = process.env['FORGE_AI_MODEL'] || DEFAULT_MODEL

/**
 * 쌓아 둔 녹음(`forge/_tape`)을 뜬 모델. **기본값이 아니라 이것에 묶는다** — 기본을 opus 로 바꿨어도
 * 녹음 174개는 sonnet 답이라, 열쇠를 기본에 묶으면 sonnet 답이 opus 답처럼 틀어진다.
 * 그래서 녹음으로 도구를 잴 때는 `FORGE_AI_MODEL=claude-sonnet-5` 를 같이 심는다(CLAUDE.md 「검증 방법」)
 */
const TAPE_MODEL = 'claude-sonnet-5'

/** 녹음 열쇠로 쓸 글. **녹음을 뜬 모델이면 브리프 그대로** — 쌓아 둔 녹음이 그대로 맞는다 */
export const tapeKey = (brief: string): string => (MODEL === TAPE_MODEL ? brief : `${brief}\n\n#model ${MODEL}`)
