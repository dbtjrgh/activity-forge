/**
 * AI 에게 줄 **뜻으로 맞추기 브리프**와, 받은 답을 **검산**하는 자리 (6단계).
 * 받은 답을 읽고 아래 ①~④를 실제로 보는 것은 `pairs.ts` 다 (2026-09-18 에 갈랐다).
 * 못 맞춘 자리를 `Slot` 으로 · 파일 갈래를 보는 셈은 `briefslots.ts` (2026-09-30 에 갈랐다).
 *
 * 남은 일이 뜻으로 맞추는 일이다 — `answer_bear` ↔ `item_bear_24.png`. 이름이
 * 회차마다 통째로 바뀌므로 규칙으로는 못 푼다(8호 76개 중 59개가 여기서 막혔다).
 *
 * **좁게 준다.** 저장소도 스펙 119장도 주지 않는다. 그 차시에서 **못 맞춘 자리와
 * 폴더에 남은 파일**만 준다 — 한 차시에 5천 토큰 안쪽이다. 좁힐수록 값도 싸고
 * 답도 정확하다.
 *
 * **설명은 스펙의 `note` 를 그대로 쓴다.** 이미 사람 읽으라고 쓴 글이다. 여기서
 * 새로 지으면 두 벌이 되고, 갈리는 날 AI 가 옛 설명을 보고 맞춘다.
 *
 * **받은 답을 믿지 않는다.** AI 는 빈칸을 싫어해서 억지로 채운다. 이 도구의
 * 제일 좋은 성질이 「짐작 안 함」인데 그것이 무너지면 **조용히 틀린 액티비티**가
 * 나온다 — 지금은 안 만들어지기라도 한다. 그래서 아래 넷을 기계가 다시 본다.
 *
 *   ① 그 파일이 폴더에 실제로 남아 있나
 *   ② 한 파일을 두 자리에 쓰지 않았나
 *   ③ 갈래가 맞나 (그림 자리에 .mp3 를 넣지 않았나)
 *   ④ 없는 별칭을 지어내지 않았나
 *
 * Electron 을 import 하지 않는다(services 규칙).
 */

import { looksRandom } from './name'
import { planBlock } from './pasted'
import type { AssetKind } from '@/gen/types'

/** 브리프에 담을 자리 하나. */
export interface Slot {
  alias: string
  kind: AssetKind
  /** 원본이 쓰던 파일 이름 — 무엇을 대신할 자리인지 알려 주는 제일 센 실마리 */
  was: string
  /** 스펙이 그 별칭에 적어 둔 글. 없으면 빈 글 */
  note: string
}

/** AI 가 돌려준 짝 하나. */
export interface Pair {
  alias: string
  file: string
  why: string
}

/** 검산 결과. 받아들인 것과 물린 것을 **둘 다** 돌려준다. */
export interface Checked {
  taken: Pair[]
  /** 물린 것과 왜 물렸는지 — 화면에 그대로 보인다 */
  refused: { alias: string; file: string; why: string }[]
  /**
   * **AI 가 「모르겠다」고 한 자리** (2026-09-21). 물린 것도 답한 것도 아니다 —
   * 사람에게 갈 물음이다. `revise.ts` 의 같은 이름과 **같은 모양**이라
   * 카드 만드는 자리(`unsureAsks`)를 같이 쓴다.
   */
  unsure: { kind: string; alias: string; why: string }[]
}

/**
 * 브리프에 **더 붙일 것들.** 첫 판은 비워 두고 두 번째 판에만 준다 —
 * 그림과 PDF 는 시간의 90%를 먹는다(저장소 함정).
 */
export interface Look {
  /** 붙여넣은 figma 화면 **전부.** 붙인 차례다 */
  shots?: string[]
  /** 붙여넣은 기획서 **전부** */
  plans?: string[]
  /** 쪽수를 세려고 쓴다. 없으면 쪽수를 말하지 않는다 */
  rscDir?: string
  /** 첫 판인데 기획서가 붙어 있다 — 기획서를 봐야 아는 소리 자리는 `?` 로 넘기게 한다 */
  planLater?: boolean
}

/**
 * 브리프 한 장. **이것이 AI 에게 가는 전부다.**
 *
 * 답을 TSV 로 받는 까닭 — 한 줄이 한 짝이라 부분만 와도 읽히고, 따옴표·괄호가
 * 어긋나서 통째로 못 읽는 일이 없다. JSON 은 한 글자만 틀려도 전부 버려진다.
 */
export function briefOf(
  code: string,
  module: string,
  origin: string,
  slots: Slot[],
  spare: string[],
  look: Look = {}
): string {
  const { shots = [], plans = [], rscDir = '', planLater = false } = look
  const rows = slots
    .map((s) => `${s.alias}\t${s.kind}\t${s.was}\t${s.note || '-'}`)
    .join('\n')
  const files = spare.join('\n')
  // **이름에 뜻이 없는 그림은 열어 보게 한다** (2026-10-01). KOL1M08W2S2 에서 낱말 그림 다섯이 `Group 11986.png` 로 왔다 —
  // 열면 「스티로폼」 글자인데 AI 는 이름만 보고 「화면에 낱말이 없다」며 `?` 를 냈다. `Read` 는 둘째 판에만 열린다(`aiargs.ts`)
  const blind = shots.length || plans.length ? spare.filter((f) => /\.(png|jpe?g|webp)$/i.test(f) && looksRandom(f)) : []

  return [
    `# 리소스 짝 맞추기 — ${code}`,
    '',
    `모듈 ${module} · 원본 ${origin} 을 베껴 이 회차를 만듭니다.`,
    '원본이 쓰던 파일 이름으로는 짝을 못 맞춘 자리가 아래에 있습니다.',
    '회차마다 낱말과 사물이 바뀌어서 이름이 다릅니다. **뜻으로** 맞춰 주세요.',
    '',
    // **화면을 맨 앞에서 읽게 한다** (2026-09-21). 전에는 화면을 붙여넣어도
    // 이 브리프만 화면을 안 봤다 — `revise`·`order`·`shape` 는 보는데 맞추기만
    // 눈을 감고 있었다. 이름으로 못 맞춘 자리야말로 **화면이 있어야 아는
    // 자리**인데 그랬다. 폴더를 울타리로 주므로 `Read` 로 열 수 있다(`ai.ts`).
    ...(shots.length
      ? [
          `## 이 회차의 figma 화면 ${shots.length}장`,
          '',
          ...shots.map((s) => `- \`${s}\``),
          '',
          '**위의 것을 다 읽고 나서 답하세요.** 아래 자리들은 이름만으로는 못 맞춘 것입니다 —',
          '무엇이 어느 자리에 몇 번째로 나오는지가 그 그림에 있습니다.',
          // 여러 장이면 왜 여러 장인지를 말해 준다 — 한 장에 다 담겼으면
          // 사람이 더 붙일 까닭이 없었다.
          ...(shots.length > 1
            ? ['**한 장에 안 보이는 자리는 다른 장에 있습니다.** 첫 장만 보고 넘기지 마세요.']
            : []),
          ''
        ]
      : []),
    // **값의 정본은 기획서다** (2026-09-23). figma 와 같은 구멍이었다 —
    // 기획서 통로를 낸 날 이름·차례·값·짜임 셋에만 잇고 **맞추기를 빠뜨렸다.**
    // 그런데 `btn_sfx_0~5` 처럼 「어느 칸에 무엇이 오나」를 정하는 것이
    // 맞추기다. 완성본 주석이 그 답을 「기획서 슬라이드 12」라고 적어 두었는데
    // 정작 그 결정을 하는 걸음이 그것을 못 보고 있었다.
    ...planBlock(plans, rscDir),
    '## 채워야 할 자리',
    '',
    '별칭\t갈래\t원본이_쓰던_파일\t스펙_설명',
    rows,
    '',
    '## 이 폴더에 남아 있는 파일 (여기 있는 것만 쓸 수 있습니다)',
    '',
    files,
    '',
    ...(blind.length
      ? [
          `**이름에 뜻이 없는 그림 ${blind.length}장은 직접 열어 보고 고르세요** — 위 경로 그대로 \`Read\` 로 열 수 있습니다.`,
          '글자만 든 그림이면 그 글자가 곧 그 낱말입니다 — 화면에 그 글자가 안 보여도 뜻으로 짝지을 수 있습니다.',
          ''
        ]
      : []),
    '## 답하는 법',
    '',
    '한 줄에 하나씩, 탭으로 나눠 주세요. 다른 말은 쓰지 마세요.',
    '',
    '별칭\t파일',
    '별칭\t?\t무엇이 있으면 알겠는지        ← **모르겠다일 때만** 셋째 칸을 씁니다',
    '',
    // **까닭 칸을 뺐다** (2026-09-21). 자리마다 한 줄씩 까닭을 쓰게 했더니
    // 나가는 글이 서너 배가 됐고 **그만큼 느려졌다** — 71자리를 물은 판이
    // 300초에 끊겼다. 그런데 그 까닭을 사람이 읽을 일이 없다(사용자 말 —
    // 「쓸모없는 문구들 다 지워」). **모르겠다일 때만** 까닭이 쓸모가 있다 —
    // 그 글이 그대로 사람에게 갈 물음이 되기 때문이다.
    '**고른 줄에는 까닭을 쓰지 마세요.** 두 칸이면 됩니다 — 글이 길면 그만큼 느립니다.',
    '',
    // **「모르면 그 줄을 쓰지 마세요」였다** (2026-09-21 에 고침). 그 말은
    // 짐작은 막았지만 **못 고른 자리를 통째로 안 보이게** 만들었다 —
    // `MAL2M07W2S1` 에서 71자리를 물어 13자리만 답이 왔고, 나머지 58자리는
    // 물린 것도 아니고 답한 것도 아니라 **아무 데도 안 남았다.** 사람이 볼
    // 수 있는 것은 에러 37개뿐이었고 왜 못 했는지는 알 길이 없었다.
    // 이제 **모르면 모른다고 적게 한다** — 그 줄이 그대로 사람에게 가는 카드가 된다.
    '- **억지로 채우지 마세요.** 짐작해서 쓰면 에러도 안 나고 아무도 모른 채 틀린',
    '  액티비티가 나갑니다 — 안 만들어지는 것보다 그것이 훨씬 나쁩니다.',
    '- **그렇다고 빈칸으로 넘어가지도 마세요.** 모르겠으면 파일 자리에 `?` 를 쓰고,',
    '  **무엇이 있으면 알 수 있는지** 적어 주세요 (화면이 잘려 있다 · 다른 장면이다 ·',
    '  소리는 화면에 안 보인다 …). 그 말이 그대로 사람에게 가는 물음이 됩니다.',
    '  **아무 줄도 안 쓰면 아무도 그 자리를 모릅니다.**',
    '- 위 목록에 **없는 파일 이름은 쓰지 마세요.** 지어내면 그 줄은 버려집니다.',
    '- **한 파일은 한 자리에만** 쓰세요.',
    '- 갈래가 맞아야 합니다 — 그림 자리에 소리 파일을 넣지 마세요.',
    '- **위에 준 자리는 하나도 빠짐없이** 한 줄씩 나와야 합니다 — 고른 것이든 `?` 든.',
    // **번호 차례로 잇는 것은 뜻이 아니다** (2026-09-28). MAL2M07W2S1 에서 원본 xylophone10~15 를
    // drum01~06 에 차례로 이었는데, 완성본은 불가사리 심벌즈가 drum05 다 — 기획서 표에만 있다.
    // 첫 판은 기획서를 안 주므로(`matchcalls.ts`) 여기서 `?` 로 넘겨야 둘째 판이 기획서를 편다.
    ...(planLater && slots.some((s) => s.kind === 'sound')
      ? [
          '- **기획서가 붙어 있습니다.** 소리는 화면에 안 보이고 파일 이름에도 뜻이 없습니다. 원본 파일과',
          '  이름 무리가 통째로 바뀐 소리 자리(예: `xylophone` → `drum`)를 **번호 차례만 보고** 잇지 마세요 —',
          '  `?` 로 두고 「기획서에서 어느 소리인지 봐야」라고 쓰면 다음 판에 기획서를 펴서 다시 묻습니다.'
        ]
      : [])
  ].join('\n')
}

/** 브리프가 대략 몇 토큰인지. 글자 수로 셈한 어림이다 — 화면에 값을 보여 주려는 것. */
export function roughTokens(brief: string): number {
  return Math.round(brief.length / 2.5)
}
