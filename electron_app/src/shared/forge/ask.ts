/** 「필요한 것」 — 사람에게 요구하는 카드. 왜 모양을 여기 적는지는 `../forge.ts` 머리말. */

import type { AnswerShape } from './answer'

// ─── 「필요한 것」 — 안 될 때 사람에게 요구하는 것 ──────────────────────
//
// 최종 목표 그림의 **오른쪽 갈래**입니다. 안 됐을 때 에러 목록만 내놓으면
// 사람은 「그래서 뭘 어쩌라고」가 됩니다. 무엇이 없는지가 아니라
// **무엇을 주면 풀리는지**를 적습니다 — 파일이면 파일, 좌표면 피그마에서
// 잰 x·y, 정할 수 없는 것이면 기획서의 그 대목.
//
// **후보는 근거가 있을 때만 냅니다.** 짐작한 후보를 확정처럼 내놓는 것이
// 제일 나쁜 실패입니다 (저장소 CLAUDE.md 6번).

/**
 * 사람에게 무엇을 달라고 하는가.
 *
 * **`모듈` 은 5단계에 더했습니다.** 배치표가 「갈림」이면 앞선 호마다 모듈이
 * 달라 기계가 못 고릅니다. 지금까지는 걸음이 넘어지며 「_layout 을 손으로
 * 고치세요」라고만 했는데, 그것이야말로 **못 정한 것 가운데 제일 큰 것**입니다
 * — 모듈이 틀리면 액티비티가 통째로 틀립니다.
 */
export type AskWant =
  | '리소스파일'
  | '고르기'
  | '좌표'
  | '값'
  | '사람이 봐야'
  | '모듈'
  | '짜임'
  | '자리세우기'
  | '원본'
  | '성우'

/** 근거 있는 후보 하나 */
export interface AskOption {
  value: string
  /** 왜 이것이 후보인가 */
  why: string
}

export interface Ask {
  id: string
  want: AskWant
  /** 무엇이 없나 — 한 줄 */
  title: string
  /** 어느 자리 */
  where: string
  /** 스펙이 그 자리에 적어 둔 설명. 없으면 빈 글 */
  desc: string
  /** 사람이 무엇을 어떤 꼴로 주면 풀리는가 */
  give: string
  options: AskOption[]
  /** 그 자리를 무엇으로 받나. 'none' 이면 앱이 받을 수 없는 것 */
  shape: AnswerShape
  /** 지금 레시피에 들어 있는 값. 고칠 때 출발점이 된다 */
  now?: unknown
  /**
   * 한 장이 몇 자리를 대신하는가. 리소스는 **이름 무리로 묶어서** 요구한다 —
   * `apple_0` 부터 `apple_11` 까지 열두 자리를 열두 장으로 내놓으면 한 차시에
   * 130장이 된다. 그것은 요구가 아니라 쏟아붓기다.
   */
  count: number
  /** 묶인 자리들의 실제 이름. 화면이 접어서 보여 준다 */
  items: string[]
  /**
   * **이 카드는 끝난 것인가.** 사람이 「확인했습니다」를 누른 자리다.
   *
   * 값으로 닫을 수 없는 카드(「사람이 봐야」)를 위한 자리다 — 안 그러면 안내
   * 한 장이 차시 전체의 쓰기를 막는다(8호 79차시 중 59차시에 한 장씩 떴다).
   *
   * **글은 안 받는다** (2026-09-16 사용자 결정). 전에는 「이렇게 하기로
   * 했습니다」를 적게 하고 그것을 `_note.md` 로 내보냈는데, 쓰는 사람에게는
   * 일만 늘고 읽는 사람은 없었다. 누른 사실만 `#seen|<카드 id>` 답으로 남는다.
   */
  done?: boolean
  /**
   * 「다음 호에도 같습니다」로 **스펙에 올릴 수 있는 자리인가** (5단계).
   *
   * 아무 답이나 올리지 않는다 — 파일 이름은 호마다 다르고, 배열 칸(`items[2]`)은
   * 칸마다 다를 수 있다. 무엇이 올릴 수 있는 것인지는 `ask.ts` 가 정한다.
   * 화면이 다시 셈하면 두 벌이 되어 갈린다.
   */
  carry: boolean
  /** 이 자리에 스펙이 이미 적어 둔 기본값의 까닭. 있으면 앞선 호에서 정한 것이다 */
  carried?: string
  /**
   * **AI 가 풀 수 없는 물음이다** — 같은 크기 그림의 차례처럼 기획이 정하는 것(2026-09-29, `askasset.ts`).
   * AI 가 한 번도 안 돈 판에서도 잠그지 않는다(`RunAsks.tsx`) — 잠그면 모듈 카드 때처럼 막다른 길이 된다
   */
  byHand?: boolean
}

/**
 * 「AI 에게 맡기기」가 풀 수 있는 카드 — 고르기 · 값. 파일이 아예 없는 것 · 모듈 · 끝난 카드는 뺀다 (2026-09-30).
 * 메인(`agent.ts`)과 화면(단추를 켤지)이 같이 본다 — 둘로 세면 단추는 켜졌는데 맡길 것이 없다가 된다
 */
export function solvable(asks: Ask[]): Ask[] {
  return asks.filter(
    (a) =>
      !a.done &&
      !['리소스파일', '모듈', '원본', '성우'].includes(a.want) &&
      ['pick', 'text', 'number'].includes(a.shape)
  )
}

/** 통째로 맡기기(`whole.ts`)의 「확인」 카드 id 앞머리 */
export const REVIEW_PREFIX = 'whole|'

/**
 * **검수 때 볼 카드** — AI 가 짐작이라 밝힌 것(2026-10-02). 미리보기를 봐야 맞는지 아는데 미리보기는 반영해야 보인다.
 * 그래서 **반영은 막지 않고 검수 완료만 막는다**(카드에 「미리보기로 확인하고」라 적어 놓고 반영을 막아 서로 걸려 있었다)
 */
export const isReview = (a: Ask): boolean => a.id.startsWith(REVIEW_PREFIX)

/** 반영 · 저절로 끝내기를 막는 카드 — 안 닫혔고 검수 카드가 아닌 것. 반영 · 차례 줄 · 작업 순서 막대가 같이 본다 */
export function blocking(asks: Ask[]): Ask[] {
  return asks.filter((a) => !a.done && !isReview(a))
}

/** 검수 완료 전에 닫아야 할 것 */
export function reviewLeft(asks: Ask[]): Ask[] {
  return asks.filter((a) => !a.done && isReview(a))
}
