// 모듈 배치표 — **비어 있는 호의 차시마다 어느 모듈이 들어가나**.
//
// 8호(M07) 영어 36차시가 껍데기만 있고 `Activity.ts` 에 모듈 import 가 없습니다.
// 무엇을 만들지 정하려면 차시마다 모듈을 알아야 하는데, WBS 에 적힌 것은
// **`E17`·`E28` 같은 활동 종류 번호**라 모듈 폴더 이름과 이어지지 않습니다.
//
// 이어 주는 것이 **차시**입니다. 학습코드 `EN L1 M07 W2 S1` 에서 호(`M07`)만
// 빼면 `L1W2S1` 이 남고, 이것은 호가 달라도 같은 차시입니다. 그 차시를 앞선
// 호에서 이미 만들어 두었으니, 거기 쓰인 모듈을 보면 빈 칸에 들어갈 것이
// 나옵니다. 코드에서는 그 `L1W2S1` 을 `slot` 이라고 부릅니다.
//
// **여기가 클론의 앞단입니다.** 전에는 원본 회차를 사람이 찾아야 했습니다 —
// `gen clone ENL1M06W2S1 ENL1M07W2S1`. 36차시를 만들려면 36번 찾습니다.
// 배치표가 있으면 만들 코드만 적으면 됩니다 — `originFor()` 가 같은 모듈을
// 쓰는 제일 가까운 호를 원본으로 골라 줍니다.
//
// **앞선 호만 봅니다.** 뒤 호는 아직 껍데기이거나(EN M08~M10) 짜임이 다릅니다 —
// EN M11 은 W1S1 이 VideoPlayer 로 시작해서 차시가 한 칸씩 어긋나 있습니다.
// 참고로 뿌려는 주되 판정에는 넣지 않습니다.
//
// **차시마다 모듈이 하나가 아닙니다.** 앞선 여섯 호를 늘어놓으면 셋으로 갈립니다.
//
//   사람    _layout/<과목><호>.json 에 적어 둔 것             → 그대로 (맨 위)
//   한가지  앞선 호가 다 같은 모듈                         → 그대로
//   교대    두 모듈이 홀·짝 호로 번갈아 나옴                → 대상 호의 홀짝 쪽
//   갈림    그 외 — 사람이 정해야 합니다
//
// **WBS 로는 판정하지 않습니다 (2026-09-03).** 한동안 「갈렸는데 WBS 번호와
// 같은 이름의 폴더가 그 차시에서 쓰인 적이 있으면 그것」이라는 규칙을 뒀는데,
// 그 규칙이 L1W1S1 을 E05 로 골랐고 **실제로는 PlaySparkLv2M2** 였습니다.
// 받은 WBS 표가 옛 정보이기도 합니다. **근거는 M01~M06 소스뿐입니다** —
// WBS 번호와 제목은 눈으로 견주라고 뿌리기만 합니다.
//
// 「교대」가 진짜입니다. `E09` 와 `E33` 이 1·3·5호 / 2·4·6호 로 딱 갈립니다.
// 두 폴더는 파일도 내용도 다른 **서로 다른 모듈**입니다 — 이름만 바뀐 것이
// 아니어서, 아무거나 골라 쓰면 안 됩니다.
//
// 영어 8호는 **33차시가 정해지고 3차시가 남습니다**(2026-09-02).

//
// **본문은 아홉 조각으로 나눴습니다** (2026-09-30, 1007줄이라 — 동작 변화 없음). 바깥(api · 명령 · 도구 · 앱)은
// 여태처럼 이 파일에서 가져다 씁니다 — 스물여섯 곳을 안 고치려고 여기서 다시 내보냅니다.
//
//   layoutcore    학습코드 꼴 · 칸 · 판정 · 사람이 적어 둔 칸 · 줄 묶기(runs)
//   layoutwbs     영어 WBS 표
//   layoutplace   차시 하나 풀기 · 화면이 물을 값(placementFor)
